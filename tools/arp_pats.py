"""The ARP view's step patterns: genre phrases built on the lowest held note. tools/tropix_params.py writes them into
src/arp_pats.h (the engine's table) and the option list of the pattern parameter.

A step is a number of semitones above the lowest held note, R (a rest) or C (a chord hit: every held note, or root,
fifth and octave when one key is held). The accent row is 0 normal, 1 accent, 2 ghost. Patterns run at the ARP RATE
(1/16 unless changed) and start at the playhead's bar, so they stay with the project."""
R, C = -128, 100

# (name, steps, accents)  accents: a string, one char per step: '.' normal, '!' accent, 'g' ghost
PATTERNS = [
    ("Kompa Pick",      [0, R, R, 7, R, 12, R, 7, 0, R, R, 7, R, 12, 7, R],      "!..g.g.. !..g.g.."),
    ("Kompa Tap",       [C, R, R, C, R, R, C, R, C, R, R, C, R, R, C, R],        "!..g..g. g..g..g."),
    ("Amapiano Log",    [0, R, R, 0, R, R, 12, R, 0, R, R, -5, R, R, 0, R],      "!..g..!. !..g..g."),
    ("Amapiano Keys",   [C, R, R, C, R, R, C, R, R, R, C, R, R, C, R, R],        "!..g..!. ..g..g.."),
    ("Soca Stab",       [C, R, C, R, R, C, R, C, C, R, C, R, R, C, R, C],        "!.g..g.. !.g..g.."),
    ("Reggae Skank",    [R, R, C, R, R, R, C, R, R, R, C, R, R, R, C, R],        "..!...!. ..!...!."),
    ("One Drop",        [R, R, R, R, R, R, R, R, C, R, R, R, R, R, R, R],        "........ !......."),
    ("Afro Pluck",      [0, R, 7, R, 12, R, R, 7, 0, R, R, 12, R, 7, R, R],      "!.g.!..g ..g.g..."),
    ("Highlife Run",    [0, 7, 12, 7, 0, 7, 12, 19, 12, 7, 12, 7, 0, -5, 0, R],  "!.g.g.g. !.g.g.g."),
    ("Gouyad Bounce",   [0, R, 0, 12, R, 7, R, 0, R, 0, R, 12, 7, R, 12, R],      "!.g..g.. .g..g.g."),
    ("Steel Pan Roll",  [0, 12, 7, 12],                                          "!g.g"),
    ("Mbira Cycle",     [0, 7, 12, R, 7, 12, 19, R, 12, 7, R, 0],                "!.g.g.!. g.g."),
    ("Slack Key",       [0, R, 12, R, 7, R, 12, R, 0, R, 12, R, 7, R, 12, 7],     "!.g.g.g. !.g.g.g."),
    ("Ukulele Strum",   [C, R, R, R, C, R, C, C, R, C, R, R, C, R, C, R],        "!...g.gg .g..g.g."),
    ("Bass Walk",       [0, R, R, 0, R, 7, R, 5, 0, R, R, 0, R, 7, R, 10],        "!..g.g.. !..g.g.."),
    ("Synth Climb",     [0, 0, 7, 7, 12, 12, 19, 19, 12, 12, 7, 7, 0, 0, -5, -5], "!g.g!g.g !g.g!g.g"),
]


def accents(a):
    return [{"!": 1, "g": 2}.get(c, 0) for c in a.replace(" ", "")]


def names():
    return [p[0] for p in PATTERNS]


def c_header():
    out = ["/* Generated by tools/tropix_params.py from tools/arp_pats.py: the ARP view's step patterns. */",
           "#define NARP_PAT %d" % len(PATTERNS),
           "static const arp_pat_t ARP_PATS[NARP_PAT] = {"]
    for name, steps, acc in PATTERNS:
        a = accents(acc)
        assert len(steps) == len(a) <= 16, name
        st = steps + [R] * (16 - len(steps))
        ac = a + [0] * (16 - len(a))
        out.append('    { "%s", %d, { %s }, { %s } },' % (name, len(steps), ", ".join("ARP_REST" if x == R else "ARP_CH" if x == C else str(x) for x in st),
                                                           ", ".join(map(str, ac))))
    out.append("};")
    return "\n".join(out) + "\n"
